// Generates src/lib/regions-data.ts: every province and kabupaten/kota with Kemendagri code and a
// centre point. Source: github.com/cahyadsn/wilayah (db/wilayah_level_1_2.sql, Kemendagri codes and names).
// Run: node scripts/build-regions.mjs [path-to-local-sql]   (downloads the SQL when no path is given)
import { readFileSync, writeFileSync } from "node:fs";

const SOURCE = "https://raw.githubusercontent.com/cahyadsn/wilayah/master/db/wilayah_level_1_2.sql";
const sql = process.argv[2]
  ? readFileSync(process.argv[2], "utf8")
  : await (await fetch(SOURCE)).text();

// ('32.04','Kabupaten Bandung','Soreang', -7.02, 107.52, ...
const row = /^\('([\d.]+)','((?:[^'\\]|''|\\.)*)','((?:[^'\\]|''|\\.)*)',\s*(-?[\d.]+|NULL),\s*(-?[\d.]+|NULL)/;
const unquote = (s) => s.replace(/''/g, "'").replace(/\\(.)/g, "$1");
const rows = sql.split("\n").flatMap((line) => {
  const m = row.exec(line);
  return m ? [{ code: m[1], name: unquote(m[2]).trim(), lat: Number(m[4]), lng: Number(m[5]) }] : [];
});

/** Same short form the app already stores: "Kab. Bandung", "Kota Bandung" (DKI "Administrasi" dropped). */
const regencyName = (name) =>
  name
    .replace(/^Kabupaten Administrasi /, "Kab. ")
    .replace(/^Kota Administrasi /, "Kota ")
    .replace(/^Kabupaten /, "Kab. ");

// ISO 3166-2 codes, which OpenStreetMap reports for a picked point (matchRegion).
const ISO = {
  11: "AC", 12: "SU", 13: "SB", 14: "RI", 15: "JA", 16: "SS", 17: "BE", 18: "LA", 19: "BB", 21: "KR",
  31: "JK", 32: "JB", 33: "JT", 34: "YO", 35: "JI", 36: "BT", 51: "BA", 52: "NB", 53: "NT",
  61: "KB", 62: "KT", 63: "KS", 64: "KI", 65: "KU", 71: "SA", 72: "ST", 73: "SN", 74: "SG", 75: "GO", 76: "SR",
  81: "MA", 82: "MU", 91: "PA", 92: "PB", 93: "PS", 94: "PT", 95: "PE", 96: "PD",
};

const round = (n) => Number(n.toFixed(4));
/** Same bounding box the disaster form enforces for coordinates. */
const inIndonesia = (r) => r.lat >= -11.5 && r.lat <= 6.5 && r.lng >= 94.5 && r.lng <= 141.5;
// Shorter names the app already stores.
const PROVINCE_NAMES = { 31: "DKI Jakarta" };
const provinces = rows.filter((r) => !r.code.includes("."));
const out = provinces.map((p) => {
  const regencies = rows
    .filter((r) => r.code.startsWith(`${p.code}.`) && Number.isFinite(r.lat) && Number.isFinite(r.lng))
    .map((r) => {
      // The source has a few typos (e.g. Wakatobi at longitude 23.5): use the province centre instead.
      const ok = inIndonesia(r);
      if (!ok) console.warn(`  koordinat di luar Indonesia, pakai titik provinsi: ${r.name} (${r.lat}, ${r.lng})`);
      const at = ok ? r : p;
      return { code: r.code, name: regencyName(r.name), latitude: round(at.lat), longitude: round(at.lng) };
    })
    .sort((a, b) => a.name.localeCompare(b.name, "id"));
  if (!ISO[p.code]) throw new Error(`no ISO code for province ${p.code} ${p.name}`);
  return { code: p.code, iso: `ID-${ISO[p.code]}`, name: PROVINCE_NAMES[p.code] ?? p.name, regencies };
});

const missing = rows.filter((r) => r.code.includes(".") && !(Number.isFinite(r.lat) && Number.isFinite(r.lng)));
console.log(`${out.length} provinsi, ${out.reduce((n, p) => n + p.regencies.length, 0)} kabupaten/kota, ${missing.length} tanpa koordinat`);
if (missing.length) console.log("tanpa koordinat:", missing.map((r) => r.name).join(", "));
for (const p of out) console.log(`  ${p.code} ${p.iso} ${p.name}: ${p.regencies.length}`);

const body = out
  .sort((a, b) => a.name.localeCompare(b.name, "id"))
  .map((p) => `  { code: ${JSON.stringify(p.code)}, iso: ${JSON.stringify(p.iso)}, name: ${JSON.stringify(p.name)}, regencies: [\n${p.regencies
    .map((r) => `    { code: ${JSON.stringify(r.code)}, name: ${JSON.stringify(r.name)}, latitude: ${r.latitude}, longitude: ${r.longitude} },`)
    .join("\n")}\n  ] },`)
  .join("\n");

writeFileSync(
  new URL("../src/lib/regions-data.ts", import.meta.url),
  `// Generated by scripts/build-regions.mjs from ${SOURCE}. Do not edit by hand.\n` +
    `// Kemendagri codes and names; latitude/longitude is the regional centre (ibu kota), used by the map (AC-27).\n\n` +
    `export const PROVINCES: {\n  code: string;\n  iso: string;\n  name: string;\n  regencies: { code: string; name: string; latitude: number; longitude: number }[];\n}[] = [\n${body}\n];\n`,
);
console.log("written src/lib/regions-data.ts");
